 * A key in here cannot be repurposed by another module, and this module cannot
 * quietly inherit another module's meaning. Genuinely universal chrome —
 * Cancel, Save, Actions, Attachments — is still read from the global file, so
 * the same button does not end up with two translations.
 *
 * Referenced as `__('collaboration.rfi.status.closed')`.
