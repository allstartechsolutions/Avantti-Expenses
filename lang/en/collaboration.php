 * These live here rather than in the global `en.json` because the module's
 * language is specific, and a word that looks generic often is not. Two bugs
 * came out of sharing: `Due` had been fixed as "A Pagar" by the payment
 * screens, where it means something payable, while here it is a deadline; and
 * `Overdue`, `Approved` and `Closed` carried the gender and number of whatever
